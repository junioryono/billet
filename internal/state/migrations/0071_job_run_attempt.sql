-- migration 71: job_run_attempt
--
-- WHICH ATTEMPT OF ITS WORKFLOW RUN A JOB WAS, as GitHub's REST job record says,
-- so that a job which failed and then passed on a re-run of the same run can be
-- told from one that failed twice or passed once. A re-run keeps its run id and
-- its commit, so the run and the attempt together are what `billet jobs stats`
-- calls flaky.
--
-- ZERO IS "NOT RECORDED", never a first attempt: GitHub numbers attempts from 1.
-- Every row from before this migration has zero, and so does a job the
-- control plane could not read, in a run of more than the sweep reads or past the
-- day it looks back. A reader leaves such a row out of a flake rate and says how
-- many it left out.
--
-- The scale-set message carries no attempt (checked in actions/scaleset v0.4.0 on
-- 2026-10-16), so the queue-time sweep fills this from the same read of the run's
-- job list that gives it the queue time.
--
-- Everything between the markers below is PUBLISHED BYTES; the prose is not.
-- Reformat one tab and every ledger that applied this migration refuses to open.

-- +billet:statement
ALTER TABLE job_history ADD COLUMN github_run_attempt INTEGER NOT NULL DEFAULT 0 CHECK (github_run_attempt >= 0)
-- +billet:end
