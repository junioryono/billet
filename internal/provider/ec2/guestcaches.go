// EVERY CACHE THE NODE SERVES TO A GUEST, ON AN EC2 GUEST (ADR-023).
//
// The firecracker guest's agent is where the mechanism lives: the DNS remap and the
// node's authority, the passthroughs, the container resolver, the relay and each
// build tool's configuration. An EC2 instance boots another way and has none of that
// agent's metadata, and a second copy of the mechanism is one that is wrong, so the
// image carries a library cut from the agent's own text, each region wrapped in a
// function, with `fetch` answered from what the boot script exported.

const (
	// guestCachesPath is where the image carries the library, which entryPointScript
	// sources.
	guestCachesPath = "/usr/local/lib/billet/guest-caches.sh"
	// guestBilletPath is billet itself in the guest, for the Go and Bazel helpers.
	guestBilletPath = "/opt/billet/bin/billet"
	// guestRunnerHome is what the agent's paths are relative to on this image.
	guestRunnerHome = "/opt/actions-runner"

	envActionsProxy = "BILLET_ACTIONS_PROXY"
	envNpmProxy     = "BILLET_NPM_PROXY"
	envActionsCA    = "BILLET_ACTIONS_CA_PEM"
	envGuestCaches  = "BILLET_GUEST_CACHES"
)

// guestCachesLibrary is the file at guestCachesPath.
func guestCachesLibrary() (string, error) {
	var b strings.Builder

	b.WriteString("# billet's guest caches on an EC2 instance, sourced by " + entryPointPath + ".\n")
	b.WriteString("# Generated by `billet ami build` from the firecracker guest's agent\n")
	b.WriteString("# (scripts/build-guest-image.sh); change it there.\n")
	b.WriteString("GUEST_BILLET=" + guestBilletPath + "\n")
	b.WriteString("BILLET_RUNNER_HOME=" + guestRunnerHome + "\n")
	b.WriteString("export BILLET_RUNNER_HOME\n")
	b.WriteString("log() { echo \"billet-guest-caches: $*\" >&2; }\n")

	// WHAT THE AGENT ASKS MMDS, answered from the boot script. Absent fails, as a key
	// the service does not hold does, and each caller already treats that as the
	// ordinary case.
	b.WriteString("fetch() {\n")
	b.WriteString("  local value\n")
	b.WriteString("  case \"$1\" in\n")
	b.WriteString("    actions-proxy) value=${" + envActionsProxy + ":-} ;;\n")
	b.WriteString("    npm-proxy) value=${" + envNpmProxy + ":-} ;;\n")
	b.WriteString("    actions-ca-pem) value=${" + envActionsCA + ":-} ;;\n")
	b.WriteString("    guest-caches) value=${" + envGuestCaches + ":-} ;;\n")
	b.WriteString("    *) return 1 ;;\n")
	b.WriteString("  esac\n")
	b.WriteString("  [ -n \"$value\" ] || return 1\n")
	b.WriteString("  printf '%s\\n' \"$value\"\n")
	b.WriteString("}\n")

	for _, region := range []struct{ name, marker string }{
		{"billet_guest_caches_prepare", "BILLET_SHARED_PREPARE"},
		{"billet_guest_caches_start", "BILLET_SHARED_START"},
		{"billet_guest_caches_relay", "BILLET_CACHE_RELAY"},
		{"billet_guest_caches_env", "BILLET_SHARED_ENV"},
	} {
		block, err := scripts.GuestImageBlock(region.marker)
		if err != nil {
			return "", fmt.Errorf("ec2: the guest caches library: %w", err)
		}
		b.WriteString(region.name + "() {\n")
		if region.marker == "BILLET_CACHE_RELAY" {
			b.WriteString("cache_relay_port=41322\n")
		}
		b.WriteString(block)
		b.WriteString("}\n")
	}

	// THE PASSTHROUGHS TUNNEL THROUGH THE RELAY, because a client's TLS cannot nest
	// inside a second TLS session on a Python socket, and the relay is a splice that
	// does not care: the node sees the CONNECT it sees from any guest. With no relay
	// there is nothing to tunnel through, so interception stays off and the job uses
	// GitHub's cache, which is the fail-open rule at the place it costs least.
	b.WriteString("billet_guest_caches_through_relay() {\n")
	b.WriteString("  local proxy\n")
	b.WriteString("  case \"$cache_endpoint\" in\n")
	b.WriteString("    http://*)\n")
	b.WriteString("      if [ -n \"$actions_proxy\" ]; then\n")
	b.WriteString("        proxy=${actions_proxy#*://}\n")
	b.WriteString("        actions_proxy=\"http://${proxy%%@*}@${cache_endpoint#http://}\"\n")
	b.WriteString("      fi\n")
	b.WriteString("      if [ -n \"$npm_proxy\" ]; then\n")
	b.WriteString("        proxy=${npm_proxy#*://}\n")
	b.WriteString("        npm_proxy=\"http://${proxy%%@*}@${cache_endpoint#http://}\"\n")
	b.WriteString("      fi\n")
	b.WriteString("      ;;\n")
	b.WriteString("    *)\n")
	b.WriteString("      if [ -n \"$actions_proxy$npm_proxy\" ]; then\n")
	b.WriteString("        log \"the cache relay did not start, so nothing can tunnel to the node; \"\n")
	b.WriteString("        log \"this job uses GitHub's cache and the registry directly\"\n")
	b.WriteString("      fi\n")
	b.WriteString("      actions_proxy=\"\"\n")
	b.WriteString("      npm_proxy=\"\"\n")
	b.WriteString("      ;;\n")
	b.WriteString("  esac\n")
	b.WriteString("}\n")

	return b.String(), nil
}

// guestCacheInstall is what the layer runs to give the image the guest half of
// every cache: the same files, installed the same way, as the firecracker guest.
// Runs as root on the builder, under `set -euo pipefail`.
func guestCacheInstall() (string, error) {
	hook, err := scripts.GuestImageBlock("BILLET_SHARED_INSTALL")
	if err != nil {
		return "", fmt.Errorf("ec2: the guest caches install: %w", err)
	}
	sudoers, err := scripts.GuestImageBlock("BILLET_SHARED_SUDOERS")
	if err != nil {
		return "", fmt.Errorf("ec2: the guest caches install: %w", err)
	}

	assets := amiRepoDir + "/internal/guestassets"

	var b strings.Builder

	b.WriteString("install -m 0755 " + assets + "/actions-proxy.py /usr/local/bin/billet-actions-proxy\n")
	b.WriteString("install -m 0755 " + assets + "/dns-upstreams.py /usr/local/bin/billet-dns-upstreams\n")
	// THE SHIM SITS AHEAD OF THE REAL CLIENT, in both places the guest build puts it,
	// and does nothing on a job the adapter is not serving.
	b.WriteString("install -m 0755 " + assets + "/docker-shim.sh /usr/local/bin/docker\n")
	b.WriteString("install -D -m 0755 " + assets + "/docker-shim.sh /opt/billet/bin/docker\n")
	b.WriteString("install -d -m 0755 /usr/local/lib/billet\n")
	b.WriteString("install -m 0644 " + assets + "/guest-caches.sh " + guestCachesPath + "\n")

	// BILLET ITSELF, staged in the payload by the billet that runs this build.
	b.WriteString("install -m 0755 " + amiGuestBilletPath + " " + guestBilletPath + "\n")
	b.WriteString(guestBilletPath + " version >/dev/null\n")
	b.WriteString("install -m 0644 " + amiRepoDir + "/internal/notices/THIRD_PARTY_NOTICES " +
		"/opt/billet/THIRD_PARTY_NOTICES\n")
	b.WriteString("cat > /opt/billet/bin/bazel-credential-helper <<'BILLETHELPEREOF'\n")
	b.WriteString("#!/bin/sh\nexec " + guestBilletPath + " cache credential-helper \"$@\"\n")
	b.WriteString("BILLETHELPEREOF\n")
	b.WriteString("chmod 0755 /opt/billet/bin/bazel-credential-helper\n")

	// THE GUEST BUILD'S OWN FUNCTIONS, run against this machine.
	b.WriteString("SCRIPT_DIR=" + amiRepoDir + "/scripts\n")
	b.WriteString("WORK=$(mktemp -d)\n")
	b.WriteString(hook)
	b.WriteString(sudoers)
	b.WriteString("install_container_hook /\n")
	b.WriteString("BILLET_RUNNER_HOME=" + guestRunnerHome + " install_cache_sudoers /\n")
	b.WriteString("rm -rf \"$WORK\"\n")

	return b.String(), nil
}

// guestCacheAssets are the guest's files the layer installs from the payload.
func guestCacheAssets() (map[string]string, error) {
	library, err := guestCachesLibrary()
	if err != nil {
		return nil, err
	}

	return map[string]string{
		"actions-proxy.py":       guestassets.ActionsProxyScript,
		"dns-upstreams.py":       guestassets.DNSUpstreamsScript,
		"docker-shim.sh":         guestassets.DockerShimScript,
		"container-hook.pin":     guestassets.ContainerHookPin,
		"container-hook.LICENSE": guestassets.ContainerHookLicense,
		"container-hook.NOTICE":  guestassets.ContainerHookNotice,
		"container-hook.js":      guestassets.ContainerHookScript,
		"guest-caches.sh":        library,
	}, nil
}

// guestCacheUserData renders what the boot script exports for the entry point.
//
// THE INTERCEPTION PROXY AND ITS AUTHORITY TRAVEL TOGETHER, as the firecracker
// backend's metadata carries them: one without the other is an interception the guest
// cannot complete, and every name here is held to what the node sent.
func guestCacheUserData(spec provider.Spec) (string, error) {
	proxied := spec.ActionsProxy != "" || spec.NpmProxy != ""
	if proxied != (spec.ActionsCAPEM != "") {
		return "", fmt.Errorf("ec2: %s needs an interception proxy and interception CA together", spec.Name)
	}
	if proxied && spec.CacheEndpoint == "" {
		return "", fmt.Errorf("ec2: %s has an interception proxy but no cache session", spec.Name)
	}
	if len(spec.GuestCaches) > 0 && spec.CacheEndpoint == "" {
		return "", fmt.Errorf("ec2: %s has guest build caches but no cache session", spec.Name)
	}

	names := make([]string, len(spec.GuestCaches))
	for i, cache := range spec.GuestCaches {
		if !cache.Valid() {
			return "", fmt.Errorf("ec2: %s names guest build cache %q, which is unknown", spec.Name, cache)
		}
		names[i] = string(cache)
	}

	var b strings.Builder
	for _, field := range []struct{ name, value string }{
		{envActionsProxy, spec.ActionsProxy},
		{envNpmProxy, spec.NpmProxy},
		{envActionsCA, spec.ActionsCAPEM},
		{envGuestCaches, strings.Join(names, ",")},
	} {
		if field.value == "" {
			continue
		}
		quoted, err := shellQuote(field.value)
		if err != nil {
			return "", fmt.Errorf("ec2: %s for %s: %w", field.name, spec.Name, err)
		}
		b.WriteString(field.name + "=" + quoted + "\n")
		b.WriteString("export " + field.name + "\n")
	}

	return b.String(), nil
}
