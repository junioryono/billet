// The steps `billet join` composes, each a seam so the order it imposes can be
// asserted against fakes: none of them can run in the suite for real (one
// fetches from a control plane, one waits for a person, one starts services).
var (
	joinFetchAuthority = func(ctx context.Context, base, fingerprint string) (string, error) {
		_, deployment, err := nodeclient.FetchCA(ctx, base, fingerprint)

		return deployment, err
	}
	joinGenerate   = setup.Init
	joinEnroll     = fleetops.EnrollNode
	joinPullImages = func(ctx context.Context, env cli.Env, cfg *config.Config) error {
		return opsimages.PullTartImages(ctx, env, cfg, "")
	}
	joinUp      = runLocalUp
	joinGOARCH  = runtime.GOARCH
	joinGeteuid = os.Geteuid
)

// joinRequest is what `billet join` was asked for.
type joinRequest struct {
	server, fingerprint, token, nodeName, bootstrapAddr string
	provider, org, repository, runnerGroup, image       string
	workflows, guestOS                                  []string
	cfgPath                                             string
	force, skipPrerequisites, hardenSSH, dryRun         bool
	// initArgs are the flags after `--`, handed to `billet init` as they are:
	// a backend's own (firecracker's kernel and Ceph identity) are init's.
	initArgs []string
}

// joinNode is `billet join`: this machine joins an existing deployment as a
// node, in one command (#181).
//
// IN THIS ORDER, each step reported, and nothing a step did undone by a later
// one failing, because each is idempotent and a re-run resumes:
//
//  1. the refusals that need nothing but the flags and the platform;
//  2. the control plane's authority, fetched and held to --ca-fingerprint
//     BEFORE ANYTHING IS WRITTEN, so a wrong fingerprint or address leaves
//     this machine as it was, and the deployment it names binds the printed
//     `billet join accept` token;
//  3. the prerequisites: on a Mac performed, under one sudo for the steps that
//     need root; on Linux verified, refusing with the fix, because the
//     Firecracker host's preparation (Ceph, the bridge, the jailer) is the
//     host role's;
//  4. the node-only config, generated by `billet init --join` itself so every
//     refusal it holds (a live control plane's config is never replaced)
//     holds here;
//  5. the enrollment, which prints this node's fingerprint and waits for an
//     operator to approve it;
//  6. on a Mac the tier images, which a node refuses to pull inside a launch;
//  7. `billet local up`.
func joinNode(ctx context.Context, env cli.Env, args []string) error {
	req, err := parseJoin(env, args)
	if err != nil {
		return err
	}

	if err := refuseJoin(req); err != nil {
		return err
	}

	base := "https://" + req.server
	if req.bootstrapAddr != "" {
		base = "https://" + req.bootstrapAddr
	}

	deployment, err := joinFetchAuthority(ctx, base, req.fingerprint)
	if err != nil {
		return fmt.Errorf("billet join: the control plane's authority at %s: %w (nothing on this machine "+
			"was changed)", base, err)
	}

	fmt.Fprintf(env.Stdout, "join     the authority at %s matches %s (deployment %s)\n", base, req.fingerprint,
		deployment)

	if req.skipPrerequisites {
		fmt.Fprintln(env.Stdout, "join     prerequisites skipped (--skip-prerequisites)")
	} else if err := joinPrerequisites(ctx, env, req); err != nil {
		return err
	}

	initArgs := joinInitArgs(req, deployment)
	if req.dryRun {
		fmt.Fprintf(env.Stdout, "join     would generate the node's config: billet init %s\n",
			cli.ShellArgs(initArgs))
		fmt.Fprintln(env.Stdout, "join     would enroll, approved on the control plane by this node's fingerprint")
		if req.provider == string(config.ProviderTart) {
			fmt.Fprintln(env.Stdout, "join     would pull the tier images")
		}
		fmt.Fprintln(env.Stdout, "join     would bring the services up (billet local up)")
		fmt.Fprintln(env.Stdout, "\nNothing was changed (--dry-run).")

		return nil
	}

	fmt.Fprintf(env.Stdout, "\njoin     generating the node's config (billet init --join)\n\n")
	if err := joinGenerate(ctx, env, initArgs); err != nil {
		return err
	}

	cfg, err := joinedConfig(req)
	if err != nil {
		return err
	}

	fmt.Fprintf(env.Stdout, "\njoin     billet join does the steps above on this machine now; the control "+
		"plane's half (`billet join accept`) and the approval are yours to run there.\n\n")

	if enrolled(cfg) {
		fmt.Fprintf(env.Stdout, "join     already enrolled: %s holds a certificate bundle\n", cfg.Node.TLS.CertPath)
	} else if err := joinEnroll(ctx, env, cfg, base, req.fingerprint, req.token); err != nil {
		return err
	}

	if cfg.Node.Provider == config.ProviderTart {
		fmt.Fprintf(env.Stdout, "\njoin     pulling the tier images\n")
		if err := joinPullImages(ctx, env, cfg); err != nil {
			return err
		}
	}

	fmt.Fprintf(env.Stdout, "\njoin     bringing the services up\n\n")

	return joinUp(ctx, env, upOptions{configPath: req.cfgPath})
}

// parseJoin reads the flags.
func parseJoin(env cli.Env, args []string) (joinRequest, error) {
	var (
		req                joinRequest
		workflows, guestOS repeatedFlag
	)

	fs := cli.NewFlagSet("billet join", env.Stdout)
	fs.StringVar(&req.server, "server", "", "the control plane's node-wire address, host:port (required)")
	fs.StringVar(&req.fingerprint, "ca-fingerprint", "", "the control plane's authority fingerprint, from "+
		"`billet ca show` or `billet ca token` (required)")
	fs.StringVar(&req.token, "token", "", "a join token from `billet ca token` (required)")
	fs.StringVar(&req.nodeName, "node-name", "", "this machine's node name (required)")
	fs.StringVar(&req.bootstrapAddr, "bootstrap-addr", "", "the control plane's enrollment address, when it "+
		"serves one apart from the node wire (`billet ca token` prints it)")
	fs.StringVar(&req.provider, "provider", defaultJoinProvider(), "this machine's backend")
	fs.StringVar(&req.org, "org", "", "the GitHub organization the deployment serves")
	fs.StringVar(&req.repository, "repository", "", "the GitHub repository the deployment serves, as owner/name")
	fs.StringVar(&req.runnerGroup, "runner-group", "", "the trusted pool's runner group")
	fs.Var(&workflows, "workflow", "a workflow the trusted pool admits (repeatable)")
	fs.Var(&guestOS, "guest-os", "tart: macos or linux (repeatable)")
	fs.StringVar(&req.image, "image", "", "the tier image")
	fs.StringVar(&req.cfgPath, "config", "", "where to write billet.yaml (defaults to the config the services "+
		"billet ships read)")
	fs.BoolVar(&req.force, "force", false, "replace an existing config billet cannot prove is its own "+
		"output (a live control plane's is never replaced)")
	fs.BoolVar(&req.skipPrerequisites, "skip-prerequisites", false, "neither perform nor verify the "+
		"prerequisites")
	fs.BoolVar(&req.hardenSSH, "harden-ssh", false, "macOS: also write the key-only sshd drop-in, "+
		"AllowUsers this account; prove a key login from a second terminal before closing this one")
	fs.BoolVar(&req.dryRun, "dry-run", false, "say what would be done, and change nothing")

	if err := fs.Parse(args); err != nil {
		return joinRequest{}, err
	}

	// EVERYTHING AFTER `--` IS INIT'S, and nothing else may be left over: a
	// positional before it is a mistyped flag.
	if rest := fs.Args(); len(rest) > 0 {
		at := len(args) - len(rest) - 1
		if at < 0 || args[at] != "--" {
			return joinRequest{}, fmt.Errorf("unexpected argument %q (pass `billet init` flags after --)", rest[0])
		}
		req.initArgs = rest
	}

	req.workflows, req.guestOS = workflows, guestOS
	if req.cfgPath == "" {
		req.cfgPath = serviceConfigPath()
	}

	for name, v := range map[string]string{
		"--server": req.server, "--ca-fingerprint": req.fingerprint, "--token": req.token,
		"--node-name": req.nodeName,
	} {
		if strings.TrimSpace(v) == "" {
			return joinRequest{}, fmt.Errorf("billet join: %s is required (`billet ca token` on the control "+
				"plane prints the whole command)", name)
		}
	}

	if err := config.ValidateNodeName("--node-name", req.nodeName); err != nil {
		return joinRequest{}, err
	}

	return req, nil
}

// refuseJoin is every refusal the flags and the platform decide.
func refuseJoin(req joinRequest) error {
	switch cli.HostOS {
	case "darwin":
		if joinGeteuid() == 0 {
			return errors.New("billet join: run it as the account that will run the node, without sudo: " +
				"a Mac's node is a launch agent in that account's GUI domain, and billet asks for sudo itself " +
				"for the steps that need root")
		}
		if req.provider == string(config.ProviderTart) && joinGOARCH != "arm64" {
			return errors.New("billet join: tart runs only on Apple silicon, and this Mac is not")
		}
	case "linux":
		if joinGeteuid() != 0 {
			return errors.New("billet join: run it as root (sudo billet join ...): the node's unit runs as " +
				"root and its config lives in /etc/billet")
		}
	default:
		return fmt.Errorf("billet join: %s is not a platform billet runs a node on", cli.HostOS)
	}

	if req.cfgPath != serviceConfigPath() {
		return fmt.Errorf("billet join: --config %s is not the config the services read (%s), and the "+
			"join ends by starting them; generate elsewhere with `billet init --join`", req.cfgPath,
			serviceConfigPath())
	}

	return nil
}

// joinInitArgs is the `billet init` the join generates the node's config with.
func joinInitArgs(req joinRequest, deployment string) []string {
	args := []string{
		"--profile", "local-service", "--config", req.cfgPath, "--provider", req.provider,
		"--join", req.server, "--join-deployment", deployment, "--node-name", req.nodeName,
	}

	for _, f := range []struct{ name, v string }{
		{"--org", req.org}, {"--repository", req.repository}, {"--runner-group", req.runnerGroup},
		{"--image", req.image},
	} {
		if f.v != "" {
			args = append(args, f.name, f.v)
		}
	}
	for _, w := range req.workflows {
		args = append(args, "--workflow", w)
	}
	for _, g := range req.guestOS {
		args = append(args, "--guest-os", g)
	}
	if req.force {
		args = append(args, "--force")
	}

	return append(args, req.initArgs...)
}

// joinedConfig loads what the generation left at the service path, and
// refuses to go on unless it is this join's node: init writes `<path>.new`
// beside a config it cannot prove is its own, and starting the services then
// would start whatever the old file says.
func joinedConfig(req joinRequest) (*config.Config, error) {
	cfg, err := config.Load(req.cfgPath)
	if err != nil {
		return nil, fmt.Errorf("billet join: load the generated config: %w", err)
	}

	if cfg.Server != nil || cfg.Node == nil || cfg.Node.ServerAddr != req.server || cfg.Node.Name != req.nodeName {
		return nil, fmt.Errorf("billet join: %s is not the node config this join generated (billet init "+
			"left it alone, above), so nothing was enrolled or started. Merge the generated file into it, "+
			"or run billet join again with --force to replace it", req.cfgPath)
	}

	if cfg.Node.TLS == nil {
		return nil, fmt.Errorf("billet join: %s names no node.tls to enroll into", req.cfgPath)
	}

	return cfg, nil
}

// enrolled reports whether the node already holds a whole bundle, so a re-run
// after the approval goes straight on.
func enrolled(cfg *config.Config) bool {
	for _, p := range []string{cfg.Node.TLS.CertPath, cfg.Node.TLS.KeyPath, cfg.Node.TLS.CAPath} {
		if info, err := os.Stat(p); err != nil || !info.Mode().IsRegular() {
			return false
		}
	}

	return true
}

// defaultJoinProvider is the backend a join assumes on this platform.
func defaultJoinProvider() string {
	if cli.HostOS == "darwin" {
		return string(config.ProviderTart)
	}

	return string(config.ProviderDocker)
}

// serviceConfigPath is the config this platform's services read; a seam,
// because a test cannot write the real one.
var serviceConfigPath = func() string {
	return initconfig.ServiceConfigPathFor(cli.HostOS)
}

// repeatedFlag is a flag given once per value.
type repeatedFlag []string

func (r *repeatedFlag) String() string { return strings.Join(*r, ",") }

func (r *repeatedFlag) Set(v string) error {
	*r = append(*r, v)

	return nil
}

var _ flag.Value = (*repeatedFlag)(nil)
