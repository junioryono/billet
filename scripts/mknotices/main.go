// Command mknotices writes internal/notices/THIRD_PARTY_NOTICES: the license of
// every module the release builds link, Go's own, and every third-party copy that
// scripts/mknotices/copies.json lists.
//
// THE LICENSES REQUIRE IT. MIT, BSD and Apache-2.0 each let billet redistribute
// what they cover on the condition that the copyright and license notice travel
// with it, and a static Go binary is a copy of every module it links. So the file
// is embedded in the binary (billet version --notices), packed into every archive,
// installed by the .deb and .rpm, and installed into the guest image.
//
// COMMITTED RATHER THAN BUILT AT RELEASE TIME, because a release builds what the
// tag says and nothing else (.goreleaser.yaml has no before hooks). The test beside
// this file regenerates it and fails when the committed file differs, so a new
// dependency cannot reach a release without its notice.
//
// VERSIONS ARE LEFT OUT ON PURPOSE. Licenses travel with the module, not the
// version, and naming versions would turn every dependency bump into a red
// build until somebody regenerated this file; a new module still does, because
// it brings a notice nobody has reproduced.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// Output is where the notices live, relative to the repository root. The binary
// embeds this file, so it is beside internal/notices/notices.go.
const Output = "internal/notices/THIRD_PARTY_NOTICES"

// targets are the platforms a release builds. .goreleaser.yaml and `make cross`
// name the same three; a module linked only on one of them is still shipped.
var targets = [][2]string{{"linux", "amd64"}, {"linux", "arm64"}, {"darwin", "arm64"}}

// Copy is one third-party copy billet keeps or installs, from copies.json.
type Copy struct {
	Name         string   `json:"name"`
	Source       string   `json:"source"`
	Pin          string   `json:"pin"`
	License      string   `json:"license"`
	LicenseFiles []string `json:"license_files"`
	// NoticeIn names the file that carries the notice inline, for a copy whose
	// license lives in a comment of the copy itself.
	NoticeIn string   `json:"notice_in"`
	Copies   []string `json:"copies"`
	Installs []string `json:"installs"`
	ShipsIn  []string `json:"ships_in"`
}

// Module is one Go module a release build links.
type Module struct {
	Path string
	Dir  string
}

// writer renders sections and files, printing each distinct license text once.
//
// ONE COPY OF AN IDENTICAL TEXT IS THE COPY THE LICENSE ASKS FOR. Forty modules
// carry the same unmodified Apache-2.0 file, and printing it forty times made the
// notices four fifths repetition. Only byte-identical texts are folded, so every
// copyright line and every NOTICE, which do differ, is still reproduced whole.
type writer struct {
	b       *bytes.Buffer
	current string
	// first maps a text to the section and file name where it was printed.
	first map[string]string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "mknotices: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	root := flag.String("root", ".", "the repository root")
	flag.Parse()

	text, err := Generate(context.Background(), *root)
	if err != nil {
		return err
	}

	return os.WriteFile(filepath.Join(*root, Output), text, 0o600)
}

// Generate renders the notices for the repository at root.
func Generate(ctx context.Context, root string) ([]byte, error) {
	copies, err := ReadCopies(root)
	if err != nil {
		return nil, err
	}

	modules, err := LinkedModules(ctx, root)
	if err != nil {
		return nil, err
	}

	goLicense, err := goRootLicense(ctx, root)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	w := &writer{b: &b, first: map[string]string{}}
	b.WriteString("Third-party notices for billet\n\n")
	b.WriteString("billet is licensed under the Apache License 2.0 (LICENSE). It contains, links or\n")
	b.WriteString("installs the third-party software below, each under its own license, which is\n")
	b.WriteString("reproduced here as that license requires. This file is generated by\n")
	b.WriteString("scripts/mknotices; regenerate it with `go run ./scripts/mknotices`.\n")

	w.section("The Go standard library", []string{
		"Source: https://go.dev",
		"License: BSD-3-Clause",
		"Ships in: the billet binary",
	})
	w.file("LICENSE", goLicense)

	if err := w.copies(root, copies); err != nil {
		return nil, err
	}

	if err := w.modules(modules); err != nil {
		return nil, err
	}

	return b.Bytes(), nil
}

func (w *writer) section(name string, lines []string) {
	w.current = name
	w.b.WriteString("\n" + strings.Repeat("=", 80) + "\n")
	w.b.WriteString(name + "\n")
	for _, l := range lines {
		w.b.WriteString(l + "\n")
	}
}

func (w *writer) file(name string, text []byte) {
	body := string(bytes.TrimRight(text, "\n"))
	if where, ok := w.first[body]; ok {
		w.b.WriteString("\n--- " + name + ": the same text as " + where + " above ---\n")

		return
	}
	w.first[body] = name + " under " + w.current
	w.b.WriteString("\n--- " + name + " ---\n\n" + body + "\n")
}

// copies writes one section per entry of copies.json, with its license files.
func (w *writer) copies(root string, copies []Copy) error {
	for i := range copies {
		c := &copies[i]
		lines := []string{"Source: " + c.Source, "Pinned at: " + c.Pin, "License: " + c.License}
		if len(c.Copies) > 0 {
			lines = append(lines, "Copied into billet's repository at: "+strings.Join(c.Copies, ", "))
		}
		if len(c.Installs) > 0 {
			lines = append(lines, "Installed at: "+strings.Join(c.Installs, "; "))
		}
		lines = append(lines, "Ships in: "+strings.Join(c.ShipsIn, "; "))
		if c.NoticeIn != "" {
			lines = append(lines, "Notice: kept in "+c.NoticeIn+", beside the copy")
		}
		w.section(c.Name, lines)

		for _, f := range c.LicenseFiles {
			text, err := os.ReadFile(filepath.Join(root, f))
			if err != nil {
				return fmt.Errorf("%s: %w", c.Name, err)
			}
			w.file(f, text)
		}
	}

	return nil
}

// modules writes one section per linked module, with its license files.
func (w *writer) modules(modules []Module) error {
	for _, m := range modules {
		files, err := LicenseFiles(m.Dir)
		if err != nil {
			return fmt.Errorf("%s: %w", m.Path, err)
		}
		// NO LICENSE FILE IS NOT "NO LICENSE". A module that ships none cannot be
		// redistributed on any terms this file could reproduce, so it is refused
		// rather than listed with nothing under it.
		if len(files) == 0 {
			return fmt.Errorf("%s, linked into billet, has no license file in %s", m.Path, m.Dir)
		}
		w.section(m.Path, []string{"Go module", "Ships in: the billet binary"})
		for _, f := range files {
			text, err := os.ReadFile(filepath.Join(m.Dir, f))
			if err != nil {
				return fmt.Errorf("%s: %w", m.Path, err)
			}
			w.file(f, text)
		}
	}

	return nil
}

// ReadCopies reads copies.json and refuses an entry that cannot be reproduced.
func ReadCopies(root string) ([]Copy, error) {
	raw, err := os.ReadFile(filepath.Join(root, "scripts", "mknotices", "copies.json"))
	if err != nil {
		return nil, err
	}

	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	var copies []Copy
	if err := dec.Decode(&copies); err != nil {
		return nil, fmt.Errorf("copies.json: %w", err)
	}

	for i := range copies {
		c := &copies[i]
		if c.Name == "" || c.Source == "" || c.Pin == "" || c.License == "" || len(c.ShipsIn) == 0 {
			return nil, fmt.Errorf("copies.json: %q needs a name, source, pin, license and ships_in", c.Name)
		}
		if len(c.LicenseFiles) == 0 && c.NoticeIn == "" {
			return nil, fmt.Errorf("copies.json: %q names neither a license file nor where its notice is", c.Name)
		}
	}

	return copies, nil
}

// LinkedModules lists every non-main module `./cmd/billet` links on any release
// target, sorted by path.
func LinkedModules(ctx context.Context, root string) ([]Module, error) {
	seen := map[string]string{}

	for _, t := range targets {
		cmd := exec.CommandContext(ctx, "go", "list", "-deps", "-json=Module", "./cmd/billet")
		cmd.Dir = root
		cmd.Env = append(os.Environ(), "GOOS="+t[0], "GOARCH="+t[1], "CGO_ENABLED=0")
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		out, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for %s/%s: %w: %s", t[0], t[1], err, stderr.String())
		}

		dec := json.NewDecoder(bytes.NewReader(out))
		for {
			var pkg struct {
				Module *struct {
					Path string
					Main bool
					Dir  string
				}
			}
			err := dec.Decode(&pkg)
			if errors.Is(err, io.EOF) {
				break
			}
			if err != nil {
				return nil, fmt.Errorf("go list for %s/%s: %w", t[0], t[1], err)
			}
			if pkg.Module == nil || pkg.Module.Main {
				continue
			}
			// AN EMPTY DIR IS A MODULE THAT IS NOT DOWNLOADED, not one with no
			// license: a notice cannot be read from nothing.
			if pkg.Module.Dir == "" {
				return nil, fmt.Errorf("%s is not in the module cache; run go mod download", pkg.Module.Path)
			}
			seen[pkg.Module.Path] = pkg.Module.Dir
		}
	}

	modules := make([]Module, 0, len(seen))
	for p, d := range seen {
		modules = append(modules, Module{Path: p, Dir: d})
	}
	sort.Slice(modules, func(i, j int) bool { return modules[i].Path < modules[j].Path })

	return modules, nil
}

// IsLicenseName reports whether a file name is one a project uses for its license,
// notice or patent grant. Go source is never one, whatever it is called.
func IsLicenseName(name string) bool {
	if strings.HasSuffix(name, ".go") {
		return false
	}
	upper := strings.ToUpper(name)
	for _, word := range []string{"LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "PATENTS"} {
		if strings.HasPrefix(upper, word) || strings.HasSuffix(upper, "."+word) {
			return true
		}
	}

	return false
}

// LicenseFiles lists a module root's license files, sorted.
func LicenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}

	var files []string
	for _, e := range entries {
		if e.Type().IsRegular() && IsLicenseName(e.Name()) {
			files = append(files, e.Name())
		}
	}
	sort.Strings(files)

	return files, nil
}

func goRootLicense(ctx context.Context, root string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, "go", "env", "GOROOT")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go env GOROOT: %w", err)
	}

	text, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(out)), "LICENSE"))
	if err != nil {
		return nil, fmt.Errorf("the Go toolchain's license: %w", err)
	}

	return text, nil
}
